"""
Experiment: Prompt ensembling (DiVeRSe + AMA) + adversarial persona critics.

Workflow:
- For each text, create 3 different "critics" by:
  - Different few-shot example slices (DiVeRSe)
  - Different query rewrites (AMA) generated by a lightweight rewrite prompt
  - Different personas (advocate / skeptic / lateral thinker)
  - Higher temperature on critics, then aggregator at temperature 0.0
- If critic labels disagree => confusing and exclude; else keep the agreed label.

Preliminary: print only. Full: save.
"""

from __future__ import annotations

import json
import os
import re
import time
from dataclasses import dataclass
from typing import Any

import numpy as np
import pandas as pd
from loguru import logger

import prompt_eng_common as pec

EXPERIMENT_SLUG = "diverse_ama_persona_ensemble"

MODEL = os.getenv("MODEL", "gemma-4-31b-it")
REWRITE_MODEL = os.getenv("REWRITE_MODEL", MODEL)

BATCH_SIZE = int(os.getenv("BATCH_SIZE", "5"))
FULL_N = int(os.getenv("FULL_N", "40"))

FEWSHOT_POOL = int(os.getenv("FEWSHOT_POOL", "20"))
FEWSHOT_K = int(os.getenv("FEWSHOT_K", "5"))

CRITIC_TEMP = float(os.getenv("CRITIC_TEMP", "0.7"))

SKIP_PRELIMINARY = pec.env_bool("SKIP_PRELIMINARY", False)
PRELIM_ONLY = pec.env_bool("PRELIM_ONLY", False)

LABELS = ["background", "objective", "methods", "results", "conclusions"]

PERSONAS = [
    ("advocate", "Your only goal is to find evidence supporting the chosen label and argue for it."),
    ("skeptic", "Your only goal is to find logical flaws and reasons the chosen label might be wrong."),
    ("lateral", "Your goal is to consider if a different label is more appropriate than the obvious one."),
]


def _extract_json_obj(raw: str) -> dict[str, Any] | None:
    raw = raw or ""
    m = re.search(r"\{[\s\S]*\}", raw)
    if not m:
        return None
    try:
        return json.loads(m.group(0))
    except Exception:
        return None


def _safe_lower(x: Any) -> str:
    return str(x).strip().lower()


@dataclass(frozen=True)
class CriticOut:
    label: str
    reasoning: str
    raw: str


def _parse_label(raw: str) -> CriticOut:
    obj = _extract_json_obj(raw) or {}
    lab = _safe_lower(obj.get("label", "error"))
    if lab not in LABELS:
        lab = "error"
    reasoning = str(obj.get("reasoning", "")).strip()
    return CriticOut(label=lab, reasoning=reasoning, raw=raw)


def rewrite_ama(text: str, *, prelim: bool) -> list[str]:
    """
    Generate 3 alternative phrasings. Returns 3 strings.
    """
    client = pec.get_openai_client(max_retries=pec.PRELIM_MAX_RETRIES if prelim else pec.MAIN_MAX_RETRIES)
    system = (
        "Rewrite the input sentence into 3 different phrasings with the same meaning.\n"
        "Return ONLY strict JSON: {\"rewrites\": [s1, s2, s3]}.\n"
        "No extra text."
    )
    user = f"Sentence:\n{text}"
    resp = client.chat.completions.create(
        model=REWRITE_MODEL,
        messages=[{"role": "system", "content": system}, {"role": "user", "content": user}],
        temperature=0.5,
        max_tokens=None,
    )
    raw = resp.choices[0].message.content or ""
    obj = _extract_json_obj(raw) or {}
    rw = obj.get("rewrites", [])
    if isinstance(rw, list):
        out = [str(x).strip() for x in rw if str(x).strip()]
        if len(out) >= 3:
            return out[:3]
    # fallback
    return [text, text, text]


def build_fewshot_block(examples: list[dict]) -> str:
    lines = []
    for ex in examples:
        lines.append(f"Text: {ex['text']}")
        lines.append(f"Label: {ex['label']}")
        lines.append("")
    return "\n".join(lines).strip()


def critic_call(
    *,
    text: str,
    fewshot: list[dict],
    persona_name: str,
    persona_desc: str,
    prelim: bool,
) -> CriticOut:
    client = pec.get_openai_client(max_retries=pec.PRELIM_MAX_RETRIES if prelim else pec.MAIN_MAX_RETRIES)
    labels_str = ", ".join(LABELS)
    fewshot_block = build_fewshot_block(fewshot)
    system = (
        f"You are {persona_name}. {persona_desc}\n"
        f"Allowed labels: [{labels_str}].\n"
        "Use the few-shot examples as guidance.\n"
        "Return ONLY strict JSON: {\"label\": <label>, \"reasoning\": <short>}\n"
    )
    user = (
        "Few-shot examples:\n"
        f"{fewshot_block}\n\n"
        "Target sentence:\n"
        f"{text}\n"
    )
    resp = client.chat.completions.create(
        model=MODEL,
        messages=[{"role": "system", "content": system}, {"role": "user", "content": user}],
        temperature=CRITIC_TEMP,
        max_tokens=None,
    )
    raw = resp.choices[0].message.content or ""
    return _parse_label(raw)


def aggregate_call(text: str, critics: list[CriticOut], *, prelim: bool) -> str:
    client = pec.get_openai_client(max_retries=pec.PRELIM_MAX_RETRIES if prelim else pec.MAIN_MAX_RETRIES)
    labels_str = ", ".join(LABELS)
    system = (
        "You are a strict judge aggregating multiple critics.\n"
        f"Allowed labels: [{labels_str}] OR output 'confusing' if critics disagree.\n"
        "Return ONLY strict JSON: {\"final_label\": <label|confusing>}."
    )
    bullets = []
    for i, c in enumerate(critics):
        bullets.append(f"Critic {i+1}: label={c.label} reasoning={c.reasoning[:250]}")
    user = "Target:\n" + text + "\n\n" + "\n".join(bullets)
    resp = client.chat.completions.create(
        model=MODEL,
        messages=[{"role": "system", "content": system}, {"role": "user", "content": user}],
        temperature=0.0,
        max_tokens=None,
    )
    raw = resp.choices[0].message.content or ""
    obj = _extract_json_obj(raw) or {}
    lab = _safe_lower(obj.get("final_label", "confusing"))
    if lab not in LABELS and lab != "confusing":
        lab = "confusing"
    return lab


def make_fewshot_pool(train_df: pd.DataFrame) -> list[dict]:
    pool = train_df.sample(n=min(FEWSHOT_POOL, len(train_df)), random_state=pec.DEFAULT_SEED).copy()
    pool["label_name"] = pool["label"].apply(pec.label_name_from_value)
    out = []
    for _, r in pool.iterrows():
        lab = str(r["label_name"]).strip().lower()
        if lab in LABELS:
            out.append({"text": str(r["text"])[:260], "label": lab})
    return out[:FEWSHOT_POOL]


def slice_fewshot(pool: list[dict], offset: int) -> list[dict]:
    # 20 pool → slices of 5: [0:5], [5:10], [10:15]
    return pool[offset : offset + FEWSHOT_K]


def run_one(text: str, true_label: str, fewshot_pool: list[dict], *, prelim: bool) -> dict[str, Any]:
    rewrites = rewrite_ama(text, prelim=prelim)
    # 3 critics: use different rewrite + different few-shot slice + different persona
    offsets = [0, 5, 10]
    critics: list[CriticOut] = []
    for (persona_name, persona_desc), rewrite, off in zip(PERSONAS, rewrites, offsets):
        fewshot = slice_fewshot(fewshot_pool, off)
        critics.append(
            critic_call(
                text=rewrite,
                fewshot=fewshot,
                persona_name=persona_name,
                persona_desc=persona_desc,
                prelim=prelim,
            )
        )

    labels = [c.label for c in critics if c.label != "error"]
    disagree = len(set(labels)) > 1 if labels else True
    if disagree:
        pred = "confusing"
    else:
        pred = labels[0] if labels else "confusing"

    # optional aggregator for logging (kept deterministic)
    agg = aggregate_call(text, critics, prelim=prelim)
    pred = agg  # let aggregator decide (includes confusing)

    return {
        "text": text[:500],
        "true": true_label,
        "rewrites": rewrites,
        "critics": [{"label": c.label, "reasoning": c.reasoning[:900]} for c in critics],
        "pred": pred,
    }


def main() -> None:
    if not pec.GOOGLE_API_KEY:
        raise ValueError("GOOGLE_API_KEY required.")

    run_dir = pec.begin_run(EXPERIMENT_SLUG)
    eval_df, _, train_df, _ = pec.load_hf_pubmed_splits()

    fewshot_pool = make_fewshot_pool(train_df)
    if len(fewshot_pool) < FEWSHOT_K:
        raise RuntimeError("Few-shot pool too small.")

    subset = eval_df.sample(n=min(FULL_N, len(eval_df)), random_state=pec.DEFAULT_SEED).copy()
    texts = subset["text"].astype(str).tolist()
    y_true = subset["label_name"].astype(str).str.lower().tolist()

    if not SKIP_PRELIMINARY and texts:
        logger.info("=== PRELIMINARY (print only): n=1 ===")
        r0 = run_one(texts[0], y_true[0], fewshot_pool, prelim=True)
        logger.info("pre true={} pred={}", r0["true"], r0["pred"])
        for i, c in enumerate(r0["critics"]):
            logger.info(" critic{} label={} reason(trunc)={}", i + 1, c["label"], c["reasoning"][:160])
        if PRELIM_ONLY:
            logger.warning("PRELIM_ONLY=1 — stop after preliminary.")
            return

    logger.info("=== FULL: n={} ===", len(texts))
    t0 = time.perf_counter()
    records = [run_one(tx, tr, fewshot_pool, prelim=False) for tx, tr in zip(texts, y_true)]
    dt = time.perf_counter() - t0

    eval_true: list[str] = []
    eval_pred: list[str] = []
    n_confusing = 0
    for r in records:
        if r["pred"] == "confusing":
            n_confusing += 1
            continue
        eval_true.append(r["true"])
        eval_pred.append(r["pred"])

    acc = float(np.mean([t == p for t, p in zip(eval_true, eval_pred)])) if eval_true else 0.0
    cr_d, cr_t = pec.sklearn_classification_reports(eval_true, eval_pred)

    pec.save_phase(
        run_dir,
        "full",
        metrics={
            "accuracy": acc,
            "n_texts": len(texts),
            "n_eval": len(eval_true),
            "n_confusing": n_confusing,
            "classification_report": cr_d,
            "classification_report_text": cr_t,
        },
        settings={
            "MODEL": MODEL,
            "REWRITE_MODEL": REWRITE_MODEL,
            "FULL_N": FULL_N,
            "FEWSHOT_POOL": FEWSHOT_POOL,
            "FEWSHOT_K": FEWSHOT_K,
            "CRITIC_TEMP": CRITIC_TEMP,
        },
        predictions=records,
        duration_seconds=dt,
        notes="Three critics with different few-shot slices, AMA rewrites, and adversarial personas; aggregator decides or confusing.",
    )

    print(cr_t)
    logger.info("Artifacts: {}", run_dir)


if __name__ == "__main__":
    main()

